// Calendário dos santos (Calendário Romano Geral + próprio do Brasil).
// Grau: S = solenidade, F = festa, M = memória, m = memória facultativa.
// `slug` é o nome do arquivo correspondente no pacote de conteúdo (quando existir).
// `cor` só é informada quando foge da regra (mártir/apóstolo = vermelho, demais = branco).

export type Grau = 'S' | 'F' | 'M' | 'm';
export type CorLiturgica = 'verde' | 'roxo' | 'branco' | 'vermelho' | 'rosa' | 'preto';

